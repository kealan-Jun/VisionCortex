def source_path(name: str) -> Path:
    """Resolve a legacy receipt key without changing historical key names."""
    module = SOURCE_MODULES.get(name.removesuffix(".py")) if name.endswith(".py") else None
    return PROJECT_ROOT / "src" / (module.replace(".", "/") + ".py") if module else PROJECT_ROOT / name
